// Guided tour: from the robustness step straight on to the H-inf step (as a visitor would), then H-inf and Play.
import { chromium } from 'playwright-core';
const out = process.argv[2] ?? 'e2e/shots';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(String(e).slice(0, 800))); page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text().slice(0, 300)); });
await page.goto('http://127.0.0.1:8001/');
await page.getByRole('button', { name: 'Take the full guided tour' }).first().click();
await page.getByRole('button', { name: /Guide step \d+: What if/ }).click(); await page.waitForTimeout(8000);
const nodes = () => page.locator('.react-flow__node').evaluateAll(ns => ns.filter(n => getComputedStyle(n).visibility !== 'hidden' && n.getBoundingClientRect().width > 2).length);
const head = () => page.locator('.coach-head b').textContent().catch(() => '?');
const log = [];
await page.locator('.coach').getByRole('button', { name: 'Show me' }).click(); await page.waitForTimeout(8000);
await page.locator('.coach').getByRole('button', { name: 'Continue' }).click(); await page.waitForTimeout(12000);
log.push(`${await head()}: nodes ${await nodes()}`); await page.screenshot({ path: `${out}/g9to10_a.png` });
await page.locator('.coach').getByRole('button', { name: 'Show me' }).click(); await page.waitForTimeout(4000);
log.push(`${await head()}: nodes ${await nodes()}`);
await page.getByRole('button', { name: 'Play through time' }).click(); await page.waitForTimeout(15000);
log.push(`after play ${await head()}: nodes ${await nodes()}, cards ${await page.locator('.pin-card').count()}`); await page.screenshot({ path: `${out}/g9to10_b.png` });
console.log(JSON.stringify({ log, errors })); process.exit(0);
